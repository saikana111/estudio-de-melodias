function traducirMensaje(texto) {
  if (MENSAJES_ES[texto]) return MENSAJES_ES[texto];
  const patrones = [
    [/^Melody has pitch classes outside the selected scale: (.*); preserved, not corrected\.$/, 'La melodía contiene clases de altura fuera de la escala elegida: $1. Se conservaron sin corregir.'],
    [/^Ensemble requires (\d+) unused non-drum MIDI channels$/, 'El ensamble necesita $1 canales MIDI libres que no sean de percusión'],
    [/^Unmatched note-off: channel (\d+), pitch (\d+)$/, 'Hay un final de nota sin inicio: canal MIDI $1, nota $2'],
    [/^Invalid configuration: (.*)$/, 'Configuración no válida: $1'],
    [/^Invalid (.*)$/, 'Valor no válido: $1']
  ];
  for (const [patron, reemplazo] of patrones) if (patron.test(texto)) return texto.replace(patron, reemplazo);
  return texto;
}
